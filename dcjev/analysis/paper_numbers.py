"""Numbers and tables of the v4 papers, computed from the committed results (never typed by hand).

    python -m dcjev.analysis.paper_numbers part1 --exp experiments --out papers/part1_control

writes <out>/numbers.tex (\\defnum{key}{value}, read by \\NUM{key}; papers/common/numbers_macro.tex) and
<out>/tables/*.tex. A paper that uses a key no script defines shows ??key?? in bold, so a missing number is visible.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

TASKS = [("Hopper-v5", "hopper", "Hopper"), ("Walker2d-v5", "walker", "Walker2d"), ("HalfCheetah-v5", "cheetah", "HalfCheetah"),
         ("Swimmer-v5", "swimmer", "Swimmer"), ("Reacher-v5", "reacher", "Reacher")]
P1_CONDS = ["env", "env_window", "kev_score", "kev_gated", "kev_distill", "ar_gated", "ar_sampled"]


def tt(name):
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def f(x, nd=2, sign=False):
    """Formatted number for LaTeX; None -> an en dash."""
    if x is None or (isinstance(x, float) and math.isnan(x)): return "--"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$").replace("+", "$+$")


class Out:
    def __init__(self, out):
        self.out = Path(out); (self.out / "tables").mkdir(parents=True, exist_ok=True)
        self.nums = {}

    def num(self, key, value):
        self.nums[key] = value

    def table(self, name, body):
        (self.out / "tables" / f"{name}.tex").write_text(body, encoding="utf-8")

    def write(self):
        lines = ["% Generated by dcjev/analysis/paper_numbers.py -- do not edit."]
        lines += [f"\\defnum{{{k}}}{{{v}}}" for k, v in sorted(self.nums.items())]
        (self.out / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{len(self.nums)} numbers -> {self.out / 'numbers.tex'}")


SHORT = {"kev_correct": "kevc", "kev_genuine": "kevg", "kev_quality": "kevq", "ar_correct": "arc", "ar_genuine": "arg",
         "ar_quality": "arq", "ar_reasoning_correct": "gen", "kev_on_track": "kevtrack", "ar_on_track": "artrack", "policy_logprob": "logprob"}


def pair_key(pair):
    """'kev_correct-ar_correct' -> 'kevcarc'."""
    return "".join(SHORT[x] for x in pair.split("-"))


def ci_nums(o, name, rest, d, nd=3, sign=False):
    """A bootstrap cell {"value", "ci95"} -> \\NUM{<name>_<rest>}, \\NUM{<name>lo_<rest>}, \\NUM{<name>hi_<rest>}."""
    o.num(f"{name}_{rest}", f(d["value"], nd, sign)); o.num(f"{name}lo_{rest}", f(d["ci95"][0], nd)); o.num(f"{name}hi_{rest}", f(d["ci95"][1], nd))


RX = ">{\\raggedright\\arraybackslash}X"   # tabularx column that takes the remaining width, ragged right


def ci_cell(d, nd=2):
    return f"{f(d['value'], nd)} \\ci{{{f(d['ci95'][0], nd)}}}{{{f(d['ci95'][1], nd)}}}"


def validation(o, exp):
    p = json.loads((exp / "validation" / "kev_parity.json").read_text())
    o.num("parity_bf16_max", f(p["parity_bf16"]["max_abs_diff"], 3))
    o.num("parity_bf16_argmax", f"{100 * p['parity_bf16']['argmax_agreement']:.1f}\\%")
    o.num("parity_fp32_max", f(p["parity_fp32"]["max_abs_diff"], 4))
    o.num("parity_questions", str(p["parity_bf16"]["questions"]))


def prompts_table(o, exp):
    """Table of the judges' task text (experiments/part1_control/prompts/judge_prompts.json), as the judges read it."""
    j = json.loads((exp / "part1_control" / "prompts" / "judge_prompts.json").read_text())
    rows = [f"{label} & {j['envs'][e]['task']} & {j['envs'][e]['reference']} & {j['envs'][e]['healthy']} \\\\" for e, _, label in TASKS]
    o.table("prompts", "\\begin{tabularx}{\\linewidth}{@{}l" + RX * 3 + "@{}}\n\\toprule\n"
            "task & task description & reference & \\texttt{healthy} question \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabularx}\n")
    o.num("progress_instruction", j["questions"]["progress"]["instructions"])


def agreement(o, res):
    # offline judge agreement on the env runs' windows
    ja = res / "judge_agreement.json"
    if ja.exists():
        j = json.loads(ja.read_text())
        sig = ["kev_progress", "kev_healthy", "kev_gated", "ar_progress", "ar_progress_sampled", "ar_healthy", "ar_gated"]
        rows, sf_rows = [], []
        for e, k, label in TASKS:
            if e not in j: continue
            d = j[e]
            cells = [f(d[x]["spearman_env_reward"]) for x in sig]
            for x in sig: o.num(f"rho_{k}_{x}", f(d[x]["spearman_env_reward"]))
            o.num(f"windows_{k}", str(d["windows"]))
            if "healthy_auroc_no_fall" in d:
                h = d["healthy_auroc_no_fall"]
                o.num(f"healthyauc_{k}_kev", f(h["kev"])); o.num(f"healthyauc_{k}_ar", f(h["ar"])); o.num(f"fallrate_{k}", f(h["fall_rate"]))
            for q, v in d.get("ar_valid_mass", {}).items(): o.num(f"validmass_{k}_{q}", f(v, 3))
            b = d.get("bootstrap")   # two-stage bootstrap over runs and their windows
            if b:
                for x in sig:
                    lo, hi = b["ci95_env_reward"][x]; o.num(f"rholo_{k}_{x}", f(lo)); o.num(f"rhohi_{k}_{x}", f(hi))
                    lo, hi = b["ci95_physical"][x]; o.num(f"rhophyslo_{k}_{x}", f(lo)); o.num(f"rhophyshi_{k}_{x}", f(hi))
                for pair, v in b["diff_env_reward"].items():
                    pk = pair.replace("_", "").replace("-", "_")
                    o.num(f"rhod_{k}_{pk}", f(v, 2, sign=True)); lo, hi = b["ci95_env_reward"][pair]
                    o.num(f"rhodlo_{k}_{pk}", f(lo)); o.num(f"rhodhi_{k}_{pk}", f(hi))
                for pair, v in b["diff_physical"].items():
                    pk = pair.replace("_", "").replace("-", "_")
                    o.num(f"rhophysd_{k}_{pk}", f(v, 2, sign=True)); lo, hi = b["ci95_physical"][pair]
                    o.num(f"rhophysdlo_{k}_{pk}", f(lo)); o.num(f"rhophysdhi_{k}_{pk}", f(hi))
            for x in sig: o.num(f"rhophys_{k}_{x}", f(d[x]["spearman_physical"]))
            rows.append(f"{label} & {d['windows']} & " + " & ".join(cells) + " \\\\")
            sf = d.get("slow_vs_fast")   # what a judge pays for standing relative to running
            if sf:
                o.num("sf_slowmax", f"{sf['slow_max_m_per_s']:g}"); o.num("sf_fastmin", f"{sf['fast_min_m_per_s']:g}")
                o.num(f"sfslow_{k}", str(sf["slow_windows"])); o.num(f"sffast_{k}", str(sf["fast_windows"]))
                for x in SF_SIGNALS:
                    xk = x.replace("_", "")
                    o.num(f"sfratio_{k}_{xk}", f(sf[x]["ratio"])); o.num(f"sfs_{k}_{xk}", f(sf[x]["slow"])); o.num(f"sff_{k}_{xk}", f(sf[x]["fast"]))
                sf_rows.append(f"{label} & {sf['slow_windows']} / {sf['fast_windows']} & " + " & ".join(f(sf[x]["ratio"]) for x in SF_SIGNALS) + " \\\\")
        for x in sig:
            v = [j[e][x]["spearman_env_reward"] for e, _, _ in TASKS if e in j and j[e][x]["spearman_env_reward"] is not None]
            o.num(f"rho_mean_{x}", f(np.mean(v)) if v else "--")
        vm = [v for e, _, _ in TASKS if e in j for v in j[e].get("ar_valid_mass", {}).values()]
        if vm: o.num("validmass_min", f(min(vm), 3))
        for q in ("progress", "healthy"):
            vq = [j[e]["ar_valid_mass"][q] for e, _, _ in TASKS if e in j and q in j[e].get("ar_valid_mass", {})]
            if vq: o.num(f"validmass_min_{q}", f(min(vq), 2)); o.num(f"validmass_max_{q}", f(max(vq), 2))
        o.table("agreement", "\\begin{tabular}{@{}lc" + "c" * len(sig) + "@{}}\n\\toprule\n & & \\multicolumn{3}{c}{\\kev{}} & "
                "\\multicolumn{4}{c}{AR judge} \\\\ \\cmidrule(lr){3-5}\\cmidrule(l){6-9}\ntask & windows & progress & healthy & gated & "
                "progress & sampled & healthy & gated \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
        if sf_rows:
            o.table("slowfast", "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n & & & \\multicolumn{2}{c}{\\kev{}} & \\multicolumn{2}{c}{AR judge} \\\\ "
                    "\\cmidrule(lr){4-5}\\cmidrule(l){6-7}\ntask & windows (slow / fast) & env.\\ reward & progress & gated & progress & gated \\\\ \\midrule\n"
                    + "\n".join(sf_rows) + "\n\\bottomrule\n\\end{tabular}\n")


SF_SIGNALS = ("per_step", "kev_progress", "kev_gated", "ar_progress", "ar_gated")
# pairs of conditions whose probability of improvement is reported per task and averaged over tasks
P1_PAIRS = [("kev_gated", "env"), ("kev_distill", "env"), ("kev_score", "env"), ("env_window", "env"), ("kev_gated", "ar_gated"),
            ("kev_score", "ar_gated"), ("kev_distill", "kev_gated"), ("kev_gated", "kev_score"), ("ar_gated", "ar_sampled"),
            ("kev_gated", "env_window")]


def behaviour(o, res):
    """What the final policies do (experiments/part1_control/results/behaviour.json, from dcjev/analysis/behaviour.py)."""
    p = res / "behaviour.json"
    if not p.exists(): return
    b = json.loads(p.read_text())
    o.num("beh_runs", str(b["runs"])); o.num("beh_maxdiff", f"{b['max_abs_return_diff']:.2g}")
    conds = [c for c in P1_CONDS if c in b["per_task"]["Hopper-v5"]] + ["random"]
    rows = []
    for c in conds:
        for e, k, _ in TASKS:
            d = b["per_task"][e].get(c)
            if not d: continue
            o.num(f"still_{k}_{c}", pct(d["still_frac"])); o.num(f"effort_{k}_{c}", f(d["effort_mean"]))
            if "flipped_frac" in d: o.num(f"flip_{k}_{c}", pct(d["flipped_frac"]))
            if "runs_flipped" in d: o.num(f"flipruns_{k}_{c}", str(d["runs_flipped"]))
            if "dist_mean" in d: o.num(f"dist_{k}_{c}", f(d["dist_mean"], 3))
        g = lambda e, key: b["per_task"][e][c].get(key)
        flips = f"{g('HalfCheetah-v5', 'runs_flipped')} of {g('HalfCheetah-v5', 'runs')}" if c != "random" else "--"
        rows.append(f"{tt(c) if c != 'random' else 'random policy'} & {pct(g('Hopper-v5', 'still_frac'))} & {pct(g('Walker2d-v5', 'still_frac'))} & "
                    f"{pct(g('Swimmer-v5', 'still_frac'))} & {flips} & {f(g('Reacher-v5', 'effort_mean'))} & {f(g('Reacher-v5', 'dist_mean'), 3)} \\\\"
                    + (" \\midrule" if c == conds[-2] else ""))
    # HalfCheetah: the returns of the runs that ended on their back against those that did not (references), and how
    # many judge-reward runs flipped
    hc = [r for r in b["per_run"] if r["env_id"] == "HalfCheetah-v5"]
    ref = [r for r in hc if r["reward"] in ("env", "env_window")]
    fl, up = [r["return_mean"] for r in ref if r["flipped_frac"] > 0.5], [r["return_mean"] for r in ref if r["flipped_frac"] <= 0.5]
    if fl and up: o.num("flip_maxret", f(max(fl), 0)); o.num("upright_minret", f(min(up), 0))
    for c in ("env", "env_window"):
        v = [r["return_mean"] for r in ref if r["reward"] == c and r["flipped_frac"] <= 0.5]
        if v: o.num(f"uprightret_{c}", f(np.mean(v), 0)); o.num(f"uprightruns_{c}", str(len(v)))
    jr = [r for r in hc if r["reward"] not in ("env", "env_window")]
    o.num("judge_runs_cheetah", str(len(jr))); o.num("judge_flipped_cheetah", str(sum(r["flipped_frac"] > 0.5 for r in jr)))
    o.table("behaviour", "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\n & Hopper & Walker2d & Swimmer & HalfCheetah & \\multicolumn{2}{c}{Reacher} \\\\ "
            "\\cmidrule(lr){2-2}\\cmidrule(lr){3-3}\\cmidrule(lr){4-4}\\cmidrule(lr){5-5}\\cmidrule(l){6-7}\n"
            "condition & still & still & still & runs flipped & effort & distance (m) \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")


def part1(o, exp):
    res = exp / "part1_control" / "results"
    prompts_table(o, exp)
    validation(o, exp)
    agreement(o, res)
    if not (res / "summary.json").exists(): return
    s = json.loads((res / "summary.json").read_text())
    conds = [c for c in P1_CONDS if c in s["aggregate"]]

    # per-task final returns (mean +- std over seeds)
    rows = []
    for e, k, label in TASKS:
        cells = []
        for c in conds:
            d = s["per_task"].get(e, {}).get(c)
            if d is None: cells.append("--"); continue
            o.num(f"ret_{k}_{c}", f(d["mean"], 0 if e != "Reacher-v5" else 1))
            o.num(f"vx_{k}_{c}", f(d["vx_mean"], 2 if e != "Swimmer-v5" else 3))
            cells.append(f"{f(d['mean'], 0 if e != 'Reacher-v5' else 1)} $\\pm$ {f(d['std'], 0 if e != 'Reacher-v5' else 1)}")
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    o.table("returns", "\\begin{tabular}{@{}l" + "c" * len(conds) + "@{}}\n\\toprule\n task & " + " & ".join(tt(c) for c in conds)
            + " \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # aggregate normalised scores
    rows = []
    for c in conds:
        g = s["aggregate"][c]
        for key, v in (("iqm", g["iqm_normalised"]), ("iqmlo", g["iqm_ci95"][0]), ("iqmhi", g["iqm_ci95"][1]),
                       ("mean", g["mean_normalised"]), ("median", g["median_normalised"]),
                       ("pimpenv", g["p_improvement_vs_env"]), ("pimpwin", g["p_improvement_vs_env_window"])):
            o.num(f"{key}_{c}", f(v))
        o.num(f"runs_{c}", str(g["runs"]))
        rows.append(f"{tt(c)} & {g['runs']} & {f(g['iqm_normalised'])} \\ci{{{f(g['iqm_ci95'][0])}}}{{{f(g['iqm_ci95'][1])}}} & "
                    f"{f(g['mean_normalised'])} & {f(g['median_normalised'])} & {f(g['p_improvement_vs_env'])} & "
                    f"{f(g['p_improvement_vs_env_window'])} \\\\")
    o.table("aggregate", "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\ncondition & runs & IQM [95\\% CI] & mean & median & "
            "$P(\\,>\\texttt{env})$ & $P(\\,>\\texttt{env\\_window})$ \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # judge cost per run and the training-time agreement of the judge scores with the environment's reward
    rows, walls = [], {}
    for c in conds:
        ds = [s["per_task"][e][c] for e, _, _ in TASKS if c in s["per_task"].get(e, {})]
        win = np.mean([d["judge_windows_mean"] for d in ds]); wait = np.mean([d["judge_wait_s_mean"] for d in ds]) / 3600
        wall = np.mean([d["wall_s_mean"] for d in ds]) / 3600; walls[c] = wall
        cor = [d["mean_corr_window_score_env"] for d in ds if d.get("mean_corr_window_score_env") is not None]
        o.num(f"judgewin_{c}", f"{win / 1000:.1f}k" if win else "0"); o.num(f"wallh_{c}", f(wall, 1)); o.num(f"waith_{c}", f(wait, 1))
        o.num(f"traincorr_{c}", f(np.mean(cor)) if cor else "--")
        rows.append(f"{tt(c)} & {f'{win:,.0f}'.replace(',', '{,}') if win else '0'} & {f(wait, 1)} & {f(wall, 1)} & {f(np.mean(cor)) if cor else '--'} \\\\")
    o.table("cost", "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\ncondition & judged windows & judge wait (h) & wall-clock (h) & "
            "corr.\\ (score, env reward) \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    judged = [walls[c] for c in conds if c not in ("env", "env_window")]
    if judged and walls.get("env"): o.num("wallratio", f"{np.mean(judged) / walls['env']:.0f}")

    o.num("ref_hopper", f(s["env_reference_return"]["Hopper-v5"], 0))
    for e, k, _ in TASKS:
        r = s["random_policy_return"][e]; o.num(f"rand_{k}", f(r, 0 if abs(r) >= 10 else 2))
    # probability of improvement P(X > Y) between conditions, per task and averaged over tasks; invariant to the
    # per-task normalisation, so computed on the returns (ties count one half)
    for a, b in P1_PAIRS:
        if a not in conds or b not in conds: continue
        ps = {}
        for e, k, _ in TASKS:
            x, y = np.array(s["per_task"][e][a]["returns"])[:, None], np.array(s["per_task"][e][b]["returns"])[None, :]
            ps[k] = float(((x > y) + 0.5 * (x == y)).mean())
        ab = f"{a.replace('_', '')}_{b.replace('_', '')}"
        for k, v in ps.items(): o.num(f"pimp_{k}_{ab}", f(v))
        o.num(f"pimp_all_{ab}", f(np.mean(list(ps.values()))))
    behaviour(o, res)
    # runs resumed from a checkpoint after a runtime reset
    rs = s["resumed_runs"]
    o.num("runs_total", str(s["runs"])); o.num("resumed_runs", str(len(rs)))
    o.num("resumed_conds", ", ".join(tt(c) for c in P1_CONDS if any(r["reward"] == c for r in rs)) or "--")
    steps = sorted({x["step"] for r in rs for x in r["resumes"]})
    o.num("resumed_steps", ", ".join(f"{x:,}".replace(",", "{,}") for x in steps) or "--")
    drop = [x["dropped_episode_steps"] for r in rs for x in r["resumes"]]
    o.num("resumed_dropped_max", str(max(drop)) if drop else "0")


BENCH_KEV = [("kev_rows_fused", "kevrows", "\\kev{}, merged, fused kernels, one row per question", "Part I judge server"),
             ("kev_shared_prefix", "kevsp", "\\kev{}, merged, shared prefix", "offline studies"),
             ("kev_backbone_8k", "kevbb", "\\kev{} on the policy's backbone", "GRPO trainers")]


def judge_cost(o, exp):
    """Idle-GPU judge costs (experiments/validation/judge_bench.json) and the shared-backbone memory check."""
    b = json.loads((exp / "validation" / "judge_bench.json").read_text())
    ms = lambda d: 1e3 * d["seconds"] / d.get("questions", d.get("prompts", d.get("judgments")))
    rows = []
    for part, k, label, use in BENCH_KEV:
        three, one = b[part]["correct+genuine+quality"], b[part]["correct"]
        o.num(f"cost_{k}3", f(ms(three), 1)); o.num(f"cost_{k}1", f(ms(one), 1))
        o.num(f"costreq_{k}3", f(1e3 * three["seconds"] / three["requests"], 1)); o.num(f"peak_{k}", f(three["peak_gb"], 1))
        rows.append(f"{label} & {use} & {f(1e3 * three['seconds'] / three['requests'], 1)} & {f(ms(three), 1)} & {f(ms(one), 1)} & "
                    f"{f(max(three['peak_gb'], one['peak_gb']), 1)} \\\\")
    ar = b["ar_fused"]
    o.num("cost_arcorrect", f(ms(ar["correct"]), 1)); o.num("cost_arquality", f(ms(ar["quality"]), 1)); o.num("peak_ar", f(ar["correct"]["peak_gb"], 1))
    rows.append(f"AR judge, fused kernels & baseline & -- & -- & {f(ms(ar['correct']), 1)} & {f(ar['correct']['peak_gb'], 1)} \\\\")
    g = b["genjudge"]
    o.num("cost_gen", f(ms(g), 0)); o.num("gen_think", f(g["think_tokens_mean"], 0)); o.num("gen_finished", pct(g["think_finished"]))
    o.num("gen_judgments", str(g["judgments"]))
    o.num("ratio_gen_kevbb", f(ms(g) / ms(b["kev_backbone_8k"]["correct+genuine+quality"]), 0))
    o.num("ratio_gen_ar", f(ms(g) / ms(ar["correct"]), 0))
    rows.append(f"AR judge reasoning first (vLLM) & baseline & -- & -- & {f(ms(g), 0)} & -- \\\\")
    o.num("bench_requests", str(b["n"]))
    o.table("judge_cost", "\\begin{tabularx}{\\linewidth}{@{}" + RX + ">{\\raggedright\\arraybackslash}p{2.2cm}cccc@{}}\n\\toprule\n"
            " & & \\multicolumn{2}{c}{3 questions} & 1 question & \\\\ "
            "\\cmidrule(lr){3-4}\\cmidrule(lr){5-5}\njudge & used by & ms/request & ms/question & ms/question & peak GB \\\\ \\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabularx}\n")
    sh = json.loads((exp / "validation" / "shared_check_idle.mem_shared.json").read_text())
    se = json.loads((exp / "validation" / "shared_check_idle.mem_separate.json").read_text())
    for k, d in (("shared", sh), ("separate", se)):
        o.num(f"mem_{k}_load", f(d["after_load_gb"], 1)); o.num(f"mem_{k}_peak", f(d["peak_gb"], 1)); o.num(f"rps_{k}", f(d["kev_requests_per_s"], 1))
        o.num(f"mem_{k}_train", f(d["peak_after_train_step_gb"], 1))
    # the training-step peak compares like with like; the overall peak also contains Kev's scoring batch, which is
    # 8192 tokens on the shared backbone (the trainers' setting) and 32768 in the separate judge's default
    o.num("mem_saving_load", pct(1 - sh["after_load_gb"] / se["after_load_gb"])); o.num("mem_saving_train", pct(1 - sh["peak_after_train_step_gb"] / se["peak_after_train_step_gb"]))
    o.num("mem_backbone_copy", f(se["after_load_gb"] - sh["after_load_gb"], 1))
    o.num("adapter_switch_ms", f(sh["adapter_switch_round_trip_ms"], 0))
    old = json.loads((exp / "validation" / "shared_check.json").read_text())
    o.num("rps_shared_contended", f(old["mem_shared"]["kev_requests_per_s"], 1))
    par = old["parity"]
    o.num("shared_parity_max", f(par["shared_backbone_unmerged"]["max_abs_diff"], 3)); o.num("shared_parity_mean", f(par["shared_backbone_unmerged"]["mean_max_abs_diff"], 4))
    o.num("shared_parity_argmax", pct(par["shared_backbone_unmerged"]["argmax_agreement"], 1))
