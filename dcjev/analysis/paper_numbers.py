"""Numbers and tables of the v4 papers, computed from the committed results (never typed by hand).

    python -m dcjev.analysis.paper_numbers part1 --exp experiments --out papers/part1_control

writes <out>/numbers.tex (\\defnum{key}{value}, read by \\NUM{key}; papers/common/numbers_macro.tex) and
<out>/tables/*.tex. A paper that uses a key no script defines shows ??key?? in bold, so a missing number is visible.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

TASKS = [("Hopper-v5", "hopper", "Hopper"), ("Walker2d-v5", "walker", "Walker2d"), ("HalfCheetah-v5", "cheetah", "HalfCheetah"),
         ("Swimmer-v5", "swimmer", "Swimmer"), ("Reacher-v5", "reacher", "Reacher")]
P1_CONDS = ["env", "env_window", "kev_score", "kev_gated", "kev_distill", "ar_gated", "ar_sampled"]


def tt(name):
    return "\\texttt{" + name.replace("_", "\\_") + "}"


def f(x, nd=2, sign=False):
    """Formatted number for LaTeX; None -> an en dash."""
    if x is None or (isinstance(x, float) and math.isnan(x)): return "--"
    s = f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"
    return s.replace("-", "$-$").replace("+", "$+$")


class Out:
    def __init__(self, out):
        self.out = Path(out); (self.out / "tables").mkdir(parents=True, exist_ok=True)
        self.nums = {}

    def num(self, key, value):
        self.nums[key] = value

    def table(self, name, body):
        (self.out / "tables" / f"{name}.tex").write_text(body, encoding="utf-8")

    def write(self):
        lines = ["% Generated by dcjev/analysis/paper_numbers.py -- do not edit."]
        lines += [f"\\defnum{{{k}}}{{{v}}}" for k, v in sorted(self.nums.items())]
        (self.out / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"{len(self.nums)} numbers -> {self.out / 'numbers.tex'}")


def validation(o, exp):
    p = json.loads((exp / "validation" / "kev_parity.json").read_text())
    o.num("parity_bf16_max", f(p["parity_bf16"]["max_abs_diff"], 3))
    o.num("parity_bf16_argmax", f"{100 * p['parity_bf16']['argmax_agreement']:.1f}\\%")
    o.num("parity_fp32_max", f(p["parity_fp32"]["max_abs_diff"], 4))
    o.num("parity_questions", str(p["parity_bf16"]["questions"]))


def part1(o, exp):
    res = exp / "part1_control" / "results"
    s = json.loads((res / "summary.json").read_text())
    conds = [c for c in P1_CONDS if c in s["aggregate"]]
    validation(o, exp)

    # per-task final returns (mean +- std over seeds)
    rows = []
    for e, k, label in TASKS:
        cells = []
        for c in conds:
            d = s["per_task"].get(e, {}).get(c)
            if d is None: cells.append("--"); continue
            o.num(f"ret_{k}_{c}", f(d["mean"], 0 if e != "Reacher-v5" else 1))
            cells.append(f"{f(d['mean'], 0 if e != 'Reacher-v5' else 1)} $\\pm$ {f(d['std'], 0 if e != 'Reacher-v5' else 1)}")
        rows.append(f"{label} & " + " & ".join(cells) + " \\\\")
    o.table("returns", "\\begin{tabular}{@{}l" + "c" * len(conds) + "@{}}\n\\toprule\n task & " + " & ".join(tt(c) for c in conds)
            + " \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # aggregate normalised scores
    rows = []
    for c in conds:
        g = s["aggregate"][c]
        for key, v in (("iqm", g["iqm_normalised"]), ("iqmlo", g["iqm_ci95"][0]), ("iqmhi", g["iqm_ci95"][1]),
                       ("mean", g["mean_normalised"]), ("median", g["median_normalised"]),
                       ("pimpenv", g["p_improvement_vs_env"]), ("pimpwin", g["p_improvement_vs_env_window"])):
            o.num(f"{key}_{c}", f(v))
        o.num(f"runs_{c}", str(g["runs"]))
        rows.append(f"{tt(c)} & {g['runs']} & {f(g['iqm_normalised'])} \\ci{{{f(g['iqm_ci95'][0])}}}{{{f(g['iqm_ci95'][1])}}} & "
                    f"{f(g['mean_normalised'])} & {f(g['median_normalised'])} & {f(g['p_improvement_vs_env'])} & "
                    f"{f(g['p_improvement_vs_env_window'])} \\\\")
    o.table("aggregate", "\\begin{tabular}{@{}lcccccc@{}}\n\\toprule\ncondition & runs & IQM [95\\% CI] & mean & median & "
            "$P(\\,>\\texttt{env})$ & $P(\\,>\\texttt{env\\_window})$ \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # judge cost per run and the training-time agreement of the judge scores with the environment's reward
    rows = []
    for c in conds:
        ds = [s["per_task"][e][c] for e, _, _ in TASKS if c in s["per_task"].get(e, {})]
        win = np.mean([d["judge_windows_mean"] for d in ds]); wait = np.mean([d["judge_wait_s_mean"] for d in ds]) / 3600
        wall = np.mean([d["wall_s_mean"] for d in ds]) / 3600
        cor = [d["mean_corr_window_score_env"] for d in ds if d.get("mean_corr_window_score_env") is not None]
        o.num(f"judgewin_{c}", f"{win / 1000:.1f}k" if win else "0"); o.num(f"wallh_{c}", f(wall, 1)); o.num(f"waith_{c}", f(wait, 1))
        o.num(f"traincorr_{c}", f(np.mean(cor)) if cor else "--")
        rows.append(f"{tt(c)} & {f'{win:,.0f}'.replace(',', '{,}') if win else '0'} & {f(wait, 1)} & {f(wall, 1)} & {f(np.mean(cor)) if cor else '--'} \\\\")
    o.table("cost", "\\begin{tabular}{@{}lcccc@{}}\n\\toprule\ncondition & judged windows & judge wait (h) & wall-clock (h) & "
            "corr.\\ (score, env reward) \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")

    # offline judge agreement on the env runs' windows
    ja = res / "judge_agreement.json"
    if ja.exists():
        j = json.loads(ja.read_text())
        sig = ["kev_progress", "kev_healthy", "kev_gated", "ar_progress", "ar_progress_sampled", "ar_healthy", "ar_gated"]
        rows = []
        for e, k, label in TASKS:
            if e not in j: continue
            d = j[e]
            cells = [f(d[x]["spearman_env_reward"]) for x in sig]
            for x in sig: o.num(f"rho_{k}_{x}", f(d[x]["spearman_env_reward"]))
            o.num(f"windows_{k}", str(d["windows"]))
            if "healthy_auroc_no_fall" in d:
                h = d["healthy_auroc_no_fall"]
                o.num(f"healthyauc_{k}_kev", f(h["kev"])); o.num(f"healthyauc_{k}_ar", f(h["ar"])); o.num(f"fallrate_{k}", f(h["fall_rate"]))
            for q, v in d.get("ar_valid_mass", {}).items(): o.num(f"validmass_{k}_{q}", f(v, 3))
            rows.append(f"{label} & {d['windows']} & " + " & ".join(cells) + " \\\\")
        for x in sig:
            v = [j[e][x]["spearman_env_reward"] for e, _, _ in TASKS if e in j and j[e][x]["spearman_env_reward"] is not None]
            o.num(f"rho_mean_{x}", f(np.mean(v)) if v else "--")
        vm = [v for e, _, _ in TASKS if e in j for v in j[e].get("ar_valid_mass", {}).values()]
        if vm: o.num("validmass_min", f(min(vm), 3))
        o.table("agreement", "\\begin{tabular}{@{}lc" + "c" * len(sig) + "@{}}\n\\toprule\n & & \\multicolumn{3}{c}{\\kev{}} & "
                "\\multicolumn{4}{c}{AR judge} \\\\ \\cmidrule(lr){3-5}\\cmidrule(l){6-9}\ntask & windows & progress & healthy & gated & "
                "progress & sampled & healthy & gated \\\\ \\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    o.num("ref_hopper", f(s["env_reference_return"]["Hopper-v5"], 0))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("part", choices=["part1"])
    ap.add_argument("--exp", default="experiments")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    o = Out(a.out)
    {"part1": part1}[a.part](o, Path(a.exp))
    o.write()


if __name__ == "__main__":
    main()
